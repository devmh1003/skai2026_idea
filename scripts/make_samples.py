def _load_library() -> list[Sample]:
    """추가 계약 5종을 붙이고, 기존 5종에 후속 협상 회차를 이어 붙인다."""
    base = [SW, SUPPLY, LEASE, NDA, OUTSOURCING]
    for sample in base:
        sample.revisions.extend(FOLLOW_UP.get(sample.contract_id, []))
    return base + EXTRA_SAMPLES


SAMPLE_SET = _load_library()


def build(sample: Sample) -> list[tuple[str, str, str]]:
    """(파일명, 라벨, 본문) 목록. v1부터 순서대로."""
    folder = SAMPLES / sample.slug
    folder.mkdir(parents=True, exist_ok=True)

    clauses = list(sample.clauses)
    out = [("v1.txt", "당사 초안", render(sample.preamble, clauses))]
    for index, revision in enumerate(sample.revisions, start=2):
        clauses = apply_revision(clauses, revision)
        out.append((f"v{index}.txt", revision.label, render(sample.preamble, clauses)))

    for name, _, text in out:
        (folder / name).write_text(text, encoding="utf-8")
    return out


def main() -> int:
    force_utf8()
    parser = argparse.ArgumentParser()
    parser.add_argument("--files-only", action="store_true", help="버전 저장소 등록 없이 파일만 생성")
    args = parser.parse_args()

    store = VersionStore(ROOT / "data" / "versions")
    for sample in SAMPLE_SET:
        versions = build(sample)
        print(f"{sample.title} ({sample.contract_id}) — {len(versions)}개 버전")

        if args.files_only:
            continue
        for name, label, _ in versions:
            path = SAMPLES / sample.slug / name
            note = next(
                (r.note for r in sample.revisions if r.label == label), "최초 작성본"
            )
            try:
                record = store.add(
                    sample.contract_id,
                    path,
                    label=label,
                    note=note,
                    title=sample.title,
                    category=sample.category,
                )
                print(f"  {record.version}  {label}")
            except ValueError as exc:
                print(f"  건너뜀: {exc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
