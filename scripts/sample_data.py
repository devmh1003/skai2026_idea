"""데모용 예시 계약 10종.

SK 계열사가 발주·위탁하는 상황을 가정해 계약 유형과 쟁점을 서로 다르게 짰다.
거래 상대방·금액·날짜·담당자는 모두 가상이며, 각 문서 첫 줄에 데모 문서임을 밝힌다.

계약마다 협상이 멈춘 지점이 다르다(`registered`). 초안만 올라온 것, 몇 차례 오간 것,
날인까지 끝난 것이 섞여 있어야 현황 화면이 실제 포트폴리오처럼 보인다.

    registered=1     개시   — 당사 초안만 등록
    registered=3~5   진행중 — 협상이 오가는 중
    registered=7     완료   — 최종 서명본까지
"""

from __future__ import annotations

from dataclasses import dataclass, field

NOTICE = "[예시] 본 문서는 제품 시연을 위해 작성된 가상 계약서입니다."


@dataclass
class Revision:
    """한 버전에서 일어난 변경."""

    label: str
    note: str = ""
    edits: dict[str, str] = field(default_factory=dict)
    """조 제목 → 새 본문."""

    drops: tuple[str, ...] = ()
    """삭제할 조 제목."""

    adds: tuple[tuple[str, str], ...] = ()
    """(제목, 본문) — 맨 뒤에 신설."""

    renames: dict[str, str] = field(default_factory=dict)
    """조 제목 변경 (내용 확장 시)."""


@dataclass
class Sample:
    slug: str
    contract_id: str
    title: str
    category: str
    preamble: str
    clauses: list[tuple[str, str]]
    revisions: list[Revision]
    registered: int = 7
    """버전 저장소에 등록할 버전 수 — 협상이 어디까지 갔는지."""


def _preamble(title: str, body: str) -> str:
    return f"{NOTICE}\n\n{title}\n\n{body}"


