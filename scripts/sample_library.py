"""추가 예시 계약 5종과 기존 계약의 후속 협상 회차.

make_samples.py가 이 모듈을 읽어 계약 10종 × 버전 7개를 만든다. 계약 유형마다
쟁점이 다르게 걸리도록(광고 성과보증, 가맹 필수품목, 운송 사고책임, 라이선스 감사,
파견 직접고용) 조문을 짰다.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Revision:
    """한 버전에서 일어난 변경."""

    label: str
    note: str = ""
    edits: dict[str, str] = field(default_factory=dict)
    """조 제목 → 새 본문."""

    drops: tuple[str, ...] = ()
    """삭제할 조 제목."""

    adds: tuple[tuple[str, str], ...] = ()
    """(제목, 본문) — 맨 뒤에 신설."""

    renames: dict[str, str] = field(default_factory=dict)
    """조 제목 변경 (내용 확장 시)."""


@dataclass
class Sample:
    slug: str
    contract_id: str
    title: str
    category: str
    preamble: str
    clauses: list[tuple[str, str]]
    revisions: list[Revision]


